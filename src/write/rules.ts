import { isToken, type TokenGroup } from "../dtcg.js";

export const START = "<!-- brandrails:start -->";
export const END = "<!-- brandrails:end -->";

const GROUP_TITLES: Record<string, string> = {
  color: "Colour",
  spacing: "Spacing",
  radius: "Radius",
  font: "Typography",
  shadow: "Shadow",
  duration: "Motion: duration",
  easing: "Motion: easing",
};

/** The rules and token tables every target shares, headed at the given level. */
export function renderRules(tokens: TokenGroup, level = 2): string {
  const h = "#".repeat(level);
  const lines = [
    `${h} Design system`,
    "",
    "Generated by Brandrails from `tokens.json`. Do not edit by hand; change `tokens.json` and regenerate.",
    "",
    "- Use these tokens for every colour, spacing, radius, font, shadow and motion value.",
    "- Never write raw hex, rgb or hsl colours, or px values for spacing and radius.",
    "- If no token fits, ask before adding a new value.",
  ];
  for (const [group, node] of Object.entries(tokens)) {
    if (isToken(node)) continue;
    lines.push("", `${h}# ${GROUP_TITLES[group] ?? group}`, "", "| Token | Value |", "| --- | --- |");
    for (const [name, token] of Object.entries(node)) {
      if (!isToken(token)) continue;
      lines.push(`| \`${group}.${name}\` | \`${token.$value.replace(/\|/g, "\\|")}\` |`);
    }
  }
  return lines.join("\n");
}

/** Inserts or replaces a marked section; everything outside the markers is preserved. */
export function upsertSection(existing: string, body: string): string {
  const section = `${START}\n${body}\n${END}`;
  const start = existing.indexOf(START);
  const end = existing.indexOf(END);
  if (start !== -1 && end > start) {
    return existing.slice(0, start) + section + existing.slice(end + END.length);
  }
  const base = existing.trimEnd();
  return (base ? `${base}\n\n` : "") + section + "\n";
}
